package sim

import (
	"math"
	"strings"
)

// OffenseRecord tracks repeated coercive or offensive actions from one actor against another
// so repeated offenses escalate exponentially rather than relying on artificial time cooldowns.
type OffenseRecord struct {
	RepeatCount int   `json:"repeat_count"`
	Accumulated int   `json:"accumulated"`
	LastTick    int64 `json:"last_tick,omitempty"`
}

// OffenseAssessment captures the continuous evaluation of one offensive/coercive action
// against a victim's dynamic breaking threshold.
type OffenseAssessment struct {
	ActionKey         string `json:"action_key"`
	Attitude          string `json:"attitude"`
	Demand            int    `json:"demand"`
	DemandRatioPct    int    `json:"demand_ratio_pct"`
	BaseOffense       int    `json:"base_offense"`
	SingleOffense     int    `json:"single_offense"`
	PriorRepeats      int    `json:"prior_repeats"`
	AccumulatedBefore int    `json:"accumulated_before"`
	AccumulatedAfter  int    `json:"accumulated_after"`
	Threshold         int    `json:"threshold"`
	Outcome           string `json:"outcome"` // "minor_favor" | "comply_resentful" | "breaking_point"
}

func offensePairKey(victimID, offenderID, actionKey string) string {
	return victimID + "|" + offenderID + "|" + actionKey
}

func normalizeOffenseAttitude(raw string) string {
	switch strings.ToLower(strings.TrimSpace(raw)) {
	case "subtle", "polite", "favor", "委婉", "试探":
		return "subtle"
	case "hostile", "threatening", "humiliating", "恶劣", "威胁", "羞辱":
		return "hostile"
	default:
		return "firm"
	}
}

// ComputeActionOffense computes the offense generated by a single coercive/offensive action
// from its base severity, relative financial/resource pain (demandRatioPct), substantive attitude,
// and exponential escalation for repeated triggers of the same behavior (2^priorRepeats).
func ComputeActionOffense(baseOffense, demandRatioPct int, attitude string, priorRepeats int) int {
	if baseOffense < 1 {
		baseOffense = 1
	}
	if demandRatioPct < 0 {
		demandRatioPct = 0
	}
	if demandRatioPct > 100 {
		demandRatioPct = 100
	}
	att := normalizeOffenseAttitude(attitude)
	attPct := 100
	switch att {
	case "subtle":
		attPct = 55
	case "hostile":
		attPct = 165
	}
	// Financial/material pain scales continuously with the fraction of victim wealth demanded.
	rawSingle := baseOffense + demandRatioPct/2
	single := maxInt(2, (rawSingle*attPct)/100)

	// Exponential escalation for repeated identical offenses against the same victim.
	if priorRepeats < 0 {
		priorRepeats = 0
	}
	if priorRepeats > 6 {
		priorRepeats = 6
	}
	mult := 1 << uint(priorRepeats)
	return single * mult
}

// ActorOffenseThreshold computes a victim's breaking threshold based on personality traits,
// power/tier asymmetry relative to the offender, and fear of leverage/exposure.
func (w *World) ActorOffenseThreshold(offender, victim Actor, leverageSeverity int) int {
	return offenseThreshold(
		victim.Personality, leverageSeverity,
		w.Catalog.PerceivedPowerTier(offender), w.Catalog.ActorPowerTier(victim),
		w.Catalog.PerceivedCombatPower(offender), CombatPowerWithCatalog(w.Catalog, victim),
	)
}

func (p Perception) ObservedOffenseThreshold(victim Neighbor, leverageSeverity int) int {
	return offenseThreshold(
		victim.Personality, leverageSeverity,
		p.Catalog.PerceivedPowerTier(p.Self), victim.PowerTier,
		p.Catalog.PerceivedCombatPower(p.Self), victim.CombatPower,
	)
}

func offenseThreshold(personality string, leverageSeverity, oTier, vTier, oPower, vPower int) int {
	threshold := 50
	switch {
	case personalityContainsAny(personality, "timid", "meek", "coward", "胆怯", "懦弱"):
		threshold += 45
	case personalityContainsAny(personality, "cautious", "humble", "easygoing", "patient", "警觉", "谦逊", "隐忍", "随和"):
		threshold += 25
	case personalityContainsAny(personality, "proud", "ruthless", "vengeful", "reckless", "righteous", "孤傲", "狠辣", "睚眦", "鲁莽", "嫉恶"):
		threshold -= 25
	}

	if leverageSeverity > 0 {
		threshold += leverageSeverity / 4
	}

	powerShift := (oTier-vTier)*15 + maxInt(-25, minInt(25, (oPower-vPower)/3))
	threshold += powerShift

	if threshold < 12 {
		threshold = 12
	}
	if threshold > 160 {
		threshold = 160
	}
	return threshold
}

// DecayedOffense applies a logarithmic forgetting/cooling curve (`1 + log10(1 + elapsedDays)`)
// to an OffenseRecord. Recent offenses retain near-100% sting so rapid repetition escalates
// exponentially, while older offenses fade quickly at first and flatten out without trivially vanishing.
func DecayedOffense(rec OffenseRecord, nowTick int64) (decayedAccum int, effectiveRepeats int) {
	if rec.Accumulated <= 0 && rec.RepeatCount <= 0 {
		return 0, 0
	}
	elapsedTicks := nowTick - rec.LastTick
	if elapsedTicks <= 0 {
		return rec.Accumulated, rec.RepeatCount
	}
	elapsedDays := float64(elapsedTicks) / float64(TicksPerDay)
	divisor := 1.0 + math.Log10(1.0+elapsedDays)
	if divisor < 1.0 {
		divisor = 1.0
	}
	decayedAccum = int(math.Round(float64(rec.Accumulated) / divisor))
	if elapsedDays >= 1.0 {
		effectiveRepeats = int(math.Floor(float64(rec.RepeatCount) / divisor))
	} else {
		effectiveRepeats = rec.RepeatCount
	}
	return decayedAccum, effectiveRepeats
}

// PreviewOffense reads the existing OffenseRecord with lg-curve time decay applied, without mutating world state.
func (w *World) PreviewOffense(victimID, offenderID, actionKey string) OffenseRecord {
	if w == nil || w.Relations == nil || w.Relations.Offenses == nil {
		return OffenseRecord{}
	}
	if rec := w.Relations.Offenses[offensePairKey(victimID, offenderID, actionKey)]; rec != nil {
		out := *rec
		out.Accumulated, out.RepeatCount = DecayedOffense(out, w.Tick)
		return out
	}
	return OffenseRecord{}
}

// AssessAndRecordOffense evaluates an offensive/coercive act using continuous demand ratio,
// attitude, lg-curve time decay on prior offenses, exponential repetition growth, and the
// victim's personality/power breaking threshold, recording the updated OffenseRecord on World.Relations.
func (w *World) AssessAndRecordOffense(victim, offender Actor, actionKey string, baseOffense, demand, victimMoney, leverageSeverity int, attitude string) OffenseAssessment {
	assessment := w.previewOffenseAssessment(victim, offender, actionKey, baseOffense, demand, victimMoney, leverageSeverity, attitude)
	rs := w.ensureRelations()
	if rs.Offenses == nil {
		rs.Offenses = map[string]*OffenseRecord{}
	}
	rs.Offenses[offensePairKey(victim.ID, offender.ID, actionKey)] = &OffenseRecord{
		RepeatCount: assessment.PriorRepeats + 1, Accumulated: assessment.AccumulatedAfter, LastTick: w.Tick,
	}
	if assessment.Outcome == "breaking_point" {
		for i := range w.Secrets {
			secret := &w.Secrets[i]
			if secret.OwnerID == offender.ID && !secret.Exposed && actorKnowsSecret(*secret, victim.ID) {
				if secret.HolderStances == nil {
					secret.HolderStances = map[string]string{}
				}
				secret.HolderStances[victim.ID] = "confront"
			}
		}
	}
	return assessment
}

func (w *World) previewOffenseAssessment(victim, offender Actor, actionKey string, baseOffense, demand, victimMoney, leverageSeverity int, attitude string) OffenseAssessment {

	att := normalizeOffenseAttitude(attitude)
	ratioPct := 0
	if demand > 0 {
		denom := victimMoney
		if denom < 1 {
			denom = 1
		}
		ratioPct = (demand * 100) / denom
		if ratioPct > 100 {
			ratioPct = 100
		}
	}

	past := w.PreviewOffense(victim.ID, offender.ID, actionKey)
	before, prior := past.Accumulated, past.RepeatCount
	single := ComputeActionOffense(baseOffense, ratioPct, att, prior)
	after := before + single
	threshold := w.ActorOffenseThreshold(offender, victim, leverageSeverity)

	outcome := "comply_resentful"
	if after >= threshold {
		outcome = "breaking_point"
	} else if after*100 < threshold*40 {
		outcome = "minor_favor"
	}

	return OffenseAssessment{
		ActionKey:         actionKey,
		Attitude:          att,
		Demand:            demand,
		DemandRatioPct:    ratioPct,
		BaseOffense:       baseOffense,
		SingleOffense:     single,
		PriorRepeats:      prior,
		AccumulatedBefore: before,
		AccumulatedAfter:  after,
		Threshold:         threshold,
		Outcome:           outcome,
	}
}

// BlackmailAssessment applies the same demand and attitude rules in previews
// and settlement. Execution alone records the resulting offense.
func (w *World) BlackmailAssessment(victim, offender Actor, secret ActorSecret, x Action, settle bool) OffenseAssessment {
	demand := x.Price
	if demand <= 0 {
		demand = maxInt(2, minInt(20, secret.Severity/4))
	}
	attitude := normalizeOffenseAttitude(x.Text)
	base := blackmailBaseOffense(demand, attitude)
	key := "blackmail:" + secret.ID
	if settle {
		return w.AssessAndRecordOffense(victim, offender, key, base, demand, victim.Money, secret.Severity, attitude)
	}
	return w.previewOffenseAssessment(victim, offender, key, base, demand, victim.Money, secret.Severity, attitude)
}

func (w *World) extortionDemand(offender, victim Actor) int {
	return minInt(victim.Money, minInt(w.Catalog.ExtortionFee(offender), victim.Money/3+1))
}

// BlackmailMinimumOffense bounds the current offense using a zero demand ratio.
func BlackmailMinimumOffense(demand int, attitude string, priorRepeats int) int {
	return ComputeActionOffense(blackmailBaseOffense(demand, attitude), 0, attitude, priorRepeats)
}

func blackmailBaseOffense(demand int, attitude string) int {
	if attitude == "subtle" && demand <= 3 {
		return 6
	}
	return 10
}
